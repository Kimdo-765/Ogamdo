#!/usr/bin/env bash
#
# start.sh — one-command bring-up for HexTech_CTF_TOOL.
#
# Brings up the core stack (redis, api, worker) AND builds the on-demand
# sandbox tool images (runner, decompiler, forensic, misc) the worker spawns
# per job. Those four sit behind `profiles: ["tools"]` in docker-compose.yml,
# so a plain `docker compose up -d` SKIPS them — and a job then dies at
# sandbox-spawn time with:
#
#     pull access denied for hextech_ctf_tool-runner, repository does not exist
#
# That exact gap silently failed job d6681eeb7288 (no_flag, exploit never ran).
# This script closes it: the tool images are always ensured before the stack
# is declared ready.
#
# Usage:
#   ./start.sh                 build any missing tool images, then bring up core
#   ./start.sh --rebuild       force-rebuild ALL images (core + tools), then up
#   ./start.sh --with-sage     additionally pull the SageMath solver image
#   ./start.sh --no-build      skip image builds; just `up -d` the core stack
#   ./start.sh --down          stop + remove the core stack and exit
#   ./start.sh -h | --help     show this help
#
# Idempotent: safe to re-run. Builds are layer-cached, so re-running when
# everything is already present costs only a few seconds.

set -euo pipefail

# --- run from the repo root no matter where we're invoked from -------------
cd "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# --- pretty output (no color when not a TTY) -------------------------------
if [ -t 1 ]; then
  B=$'\033[1m'; G=$'\033[32m'; Y=$'\033[33m'; R=$'\033[31m'; C=$'\033[36m'; N=$'\033[0m'
else
  B=''; G=''; Y=''; R=''; C=''; N=''
fi
say()  { printf '%s==>%s %s\n' "$B" "$N" "$*"; }
ok()   { printf '  %s✓%s %s\n' "$G" "$N" "$*"; }
warn() { printf '  %s!%s %s\n' "$Y" "$N" "$*"; }
die()  { printf '  %s✗%s %s\n' "$R" "$N" "$*" >&2; exit 1; }

# --- the four on-demand images and their compose service names -------------
TOOL_IMAGES=(hextech_ctf_tool-runner hextech_ctf_tool-decompiler \
             hextech_ctf_tool-forensic hextech_ctf_tool-misc \
             hextech_ctf_tool-vpn)
TOOL_SERVICES=(decompiler forensic misc runner vpn)   # compose builds by service name

# --- flags -----------------------------------------------------------------
REBUILD=0; WITH_SAGE=0; NO_BUILD=0; DOWN=0
for arg in "$@"; do
  case "$arg" in
    --rebuild)   REBUILD=1 ;;
    --with-sage) WITH_SAGE=1 ;;
    --no-build)  NO_BUILD=1 ;;
    --down)      DOWN=1 ;;
    -h|--help)
      sed -n '2,26p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
      exit 0 ;;
    *) die "unknown option: $arg (try --help)" ;;
  esac
done

# --- preflight: docker + compose -------------------------------------------
# Docker Desktop may leave a non-functional Windows shim earlier on PATH even
# when this WSL distro's snap Docker daemon is the one actually serving the
# project. Prefer that local daemon when it is installed and reachable.
if [ -x /snap/bin/docker ] && /snap/bin/docker info >/dev/null 2>&1; then
  export PATH="/snap/bin:$PATH"
fi
command -v docker >/dev/null 2>&1 || die "docker not found on PATH"
if docker compose version >/dev/null 2>&1; then
  DC=(docker compose)
elif command -v docker-compose >/dev/null 2>&1; then
  DC=(docker-compose)
else
  die "neither 'docker compose' nor 'docker-compose' is available"
fi
docker info >/dev/null 2>&1 || die "docker daemon not reachable (is it running? do you have permission?)"

# --- stale KVM override guard (must run before ANY compose command) ---------
# start.sh generates docker-compose.override.yml to pass /dev/kvm through, and
# that file names SERVICES. The worker split renamed them (worker ->
# worker-1/worker-2), so an override written before the split declares a
# service that no longer exists AND has no image or build context. Compose
# rejects the whole project:
#     service "worker" has neither an image nor a build context specified:
#     invalid compose project
# — which breaks every compose command, including the ones that would fix it.
#
# The file self-identifies with start.sh's marker, so when it is ours we may
# drop it. The move-test is what makes this safe: the override is only removed
# when removing it DEMONSTRABLY repairs the project, never merely because some
# unrelated compose error occurred.
_heal_stale_override() {
  local ovr=docker-compose.override.yml bak
  [ -f "$ovr" ] || return 0
  head -1 "$ovr" 2>/dev/null \
    | grep -qxF "# AUTO-GENERATED by start.sh: KVM device passthrough" || return 0
  "${DC[@]}" config --services >/dev/null 2>&1 && return 0
  bak="${ovr}.stale.$$"
  mv "$ovr" "$bak" 2>/dev/null || return 0
  if "${DC[@]}" config --services >/dev/null 2>&1; then
    warn "removed a STALE generated $ovr — it named a worker service that no"
    warn "longer exists and broke every docker compose command. Re-run ./start.sh"
    warn "to regenerate it with the current slot names (KVM stays off until then)."
    rm -f "$bak"
  else
    mv "$bak" "$ovr" 2>/dev/null || true
  fi
}
_heal_stale_override

# --- pre-split worker container guard ---------------------------------------
# The worker is now one container per slot (worker-1, worker-2), and each pins
# its container_name. A pre-split `worker` container already HOLDS the name
# worker-1 wants, and `up` cannot resolve that: verified on docker compose v2,
# `up -d --force-recreate` half-migrates — worker-2 is Created but never
# started, worker-1 dies on
#     Conflict. The container name "/..." is already in use
# and the old container keeps running. Half-migrated is worse than not
# migrated, so refuse and print the fix instead of walking into it.
#
# Removing the old container is deliberately NOT automatic here: start.sh is
# run casually and that container may be running a job. restart.sh, whose
# contract is already "hard reset, kills jobs", does remove it.
_legacy_worker_ids() {
  docker ps -aq \
    --filter "label=com.docker.compose.project=hextech_ctf_tool" \
    --filter "label=com.docker.compose.service=worker" 2>/dev/null
}
# Gated on $DOWN: `./start.sh --down` (the short-circuit just below) is the
# escape hatch an operator reaches for when a migration goes sideways, and
# `down` removes containers by service, so it neither hits nor cares about the
# name conflict. Refusing there would disable the one command that helps.
if [ "$DOWN" -eq 0 ] && [ -n "$(_legacy_worker_ids)" ] \
   && "${DC[@]}" config --services 2>/dev/null | grep -qxE 'worker-[0-9]+'; then
  warn "a pre-split 'worker' container is still present, but this compose file"
  warn "defines worker slots. 'up' would half-migrate (name conflict on"
  warn "hextech_ctf_tool-worker-1). Finish the one-time migration first:"
  warn "    rm -f docker-compose.override.yml"
  warn "    docker rm -f hextech_ctf_tool-worker-1"
  warn "    ./start.sh"
  die  "refusing to continue (no changes made)"
fi

# --- --down short-circuit --------------------------------------------------
if [ "$DOWN" -eq 1 ]; then
  say "Stopping core stack"
  "${DC[@]}" down
  ok "stopped"
  exit 0
fi

# --- .env --------------------------------------------------------------------
if [ ! -f .env ]; then
  if [ -f .env.example ]; then
    cp .env.example .env
    warn ".env was missing — copied from .env.example."
    warn "Edit it (HOST_DATA_DIR to the absolute path of $(pwd)/data) before real use."
  else
    die ".env is missing and no .env.example to seed it from"
  fi
fi

# --- auth hint (non-fatal) -------------------------------------------------
# Pin mount sources so compose substitution is stable under sudo / different shells.
export HOST_CLAUDE_HOME="${HOST_CLAUDE_HOME:-$HOME/.claude}"
export HOST_GROK_HOME="${HOST_GROK_HOME:-$HOME/.grok}"
CODEX_LOGIN_HOME="$HOME/.codex"
export HOST_CODEX_HOME="${HOST_CODEX_HOME:-$HOME/.codex-hextech}"
CLAUDE_HOME="$HOST_CLAUDE_HOME"
if [ ! -d "$CLAUDE_HOME" ]; then
  warn "Claude config dir not found at $CLAUDE_HOME."
  warn "Run 'claude login' on the host for OAuth, or set ANTHROPIC_API_KEY in .env / Settings."
fi
if [ ! -f "$HOST_GROK_HOME/auth.json" ] && [ -z "${XAI_API_KEY:-}" ]; then
  warn "No Grok auth at $HOST_GROK_HOME/auth.json and XAI_API_KEY unset."
  warn "Run 'grok login' or set XAI_API_KEY if you plan to use agent_provider=grok."
fi
if [ "$HOST_CODEX_HOME" = "$CODEX_LOGIN_HOME" ]; then
  die "HOST_CODEX_HOME points at the live TUI home ($CODEX_LOGIN_HOME). Root containers can rewrite config.toml as root; use $HOME/.codex-hextech."
else
  bash scripts/init-codex-runtime-home.sh "$CODEX_LOGIN_HOME" "$HOST_CODEX_HOME"
fi
if [ ! -s "$HOST_CODEX_HOME/auth.json" ]; then
  warn "No Codex file-backed auth at $HOST_CODEX_HOME/auth.json."
  warn "Run 'codex login' on the host, then re-run start.sh to bootstrap it."
fi

# --- which tool images are missing -----------------------------------------
missing=()
for img in "${TOOL_IMAGES[@]}"; do
  docker image inspect "$img" >/dev/null 2>&1 || missing+=("$img")
done

# --- build tool images ------------------------------------------------------
if [ "$NO_BUILD" -eq 1 ]; then
  if [ "${#missing[@]}" -gt 0 ]; then
    warn "--no-build set, but these tool images are MISSING: ${missing[*]}"
    warn "Jobs will fail at sandbox-spawn until you build them (drop --no-build)."
  fi
elif [ "$REBUILD" -eq 1 ]; then
  say "Force-rebuilding tool images: ${TOOL_SERVICES[*]}"
  "${DC[@]}" --profile tools build "${TOOL_SERVICES[@]}"
  ok "tool images rebuilt"
elif [ "${#missing[@]}" -gt 0 ]; then
  say "Building missing tool images (${missing[*]})"
  "${DC[@]}" --profile tools build "${TOOL_SERVICES[@]}"
  ok "tool images built"
else
  ok "all 4 tool images already present — skipping build (use --rebuild to force)"
fi

# --- optional SageMath solver image ----------------------------------------
if [ "$WITH_SAGE" -eq 1 ]; then
  say "Pulling SageMath solver image (sage profile)"
  "${DC[@]}" --profile tools-sage pull sage
  ok "sage image pulled"
fi

# --- stop any stale cloudflared OOB tunnel from a prior run -----------------
# The tunnel runs as a docker-run SIBLING (hextech_ctf_tool_tunnel, label
# hextech_ctf_tool_role=tunnel), NOT a compose service; a stale one would keep
# pointing at the old api and hold a dead Callback URL. Reap it before bringing
# the stack up — re-activate via Settings > Activate tunnel afterwards.
say "Removing any stale cloudflared tunnel sibling container"
docker rm -f hextech_ctf_tool_tunnel >/dev/null 2>&1 && ok "removed stale hextech_ctf_tool_tunnel" || true
for c in $(docker ps -aq --filter "label=hextech_ctf_tool_role=tunnel" 2>/dev/null); do
  docker rm -f "$c" >/dev/null 2>&1 || true
done

# --- core-dump sink guard (WSL) --------------------------------------------
# Deliberately CRASHING the challenge binary is a normal method here: a V8 job
# SIGTRAPs d8 dozens of times probing aborting bounds checks, kernel-pwn jobs
# panic qemu, and every fuzzing sweep segfaults something. On WSL the default
#     /proc/sys/kernel/core_pattern = |/wsl-capture-crash %t %E %p %s
# pipes EVERY one of those to %TEMP%\wsl-crashes on the WINDOWS C: DRIVE. d8
# reserves a multi-GB pointer-compression cage, so the dumps are enormous:
# 2026-07-28, twelve d8 crashes from two jobs wrote 423 GB in a single day and
# took C: down to 1.5 GB free. The container already sets RLIMIT_CORE=0, but
# the kernel IGNORES RLIMIT_CORE when core_pattern is a PIPE — so ulimit does
# not save you. A non-pipe pattern makes the limit effective again and no dump
# is written at all. Warn only: this is a HOST sysctl and start.sh must not
# need root.
if [ -r /proc/sys/kernel/core_pattern ]; then
  CP="$(cat /proc/sys/kernel/core_pattern 2>/dev/null || echo)"
  case "$CP" in
    \|*)
      warn "core_pattern is a PIPE ($CP)"
      warn "  Crashing challenge binaries (d8 SIGTRAP, qemu panics, fuzzing)"
      warn "  will be dumped by the host — on WSL that lands on the Windows"
      warn "  C: drive and can reach hundreds of GB in a day. Fix once:"
      warn "    echo 'kernel.core_pattern=core' | sudo tee /etc/sysctl.d/99-no-crash-dump.conf"
      warn "    sudo sysctl -p /etc/sysctl.d/99-no-crash-dump.conf"
      ;;
    *) ok "core_pattern=$CP (not a pipe — container RLIMIT_CORE=0 is effective)" ;;
  esac
fi

# --- KVM passthrough for pwn KERNEL challenges (host-conditional) -----------
# The worker's qemu-system-x86_64 can boot a challenge's own kernel under KVM
# only if the host's /dev/kvm is passed into the container. A hard `devices:`
# entry in docker-compose.yml would make `up` FAIL on any host without
# /dev/kvm (no nested virt, CI, macOS), so the committed compose stays
# portable and we generate an OPTIONAL override that Compose auto-merges ONLY
# when the device is present. Gate: /dev/kvm exists AND ENABLE_KVM != 0.
#
# ENABLE_KVM precedence: shell env > .env value > default(1). start.sh does
# NOT `source` .env (it only greps individual keys, like WEB_PORT L~209), so
# read the value the same way. The `|| true` is load-bearing: under this
# script's `set -euo pipefail`, a grep that finds no ENABLE_KVM line returns 1
# and would ABORT the whole startup — WEB_PORT/AUTO_TUNNEL only get away with
# the bare pattern because those keys are always present in .env; ENABLE_KVM
# usually is not.
#
# The override self-identifies by an EXACT first-line marker (so a hand-
# authored file that merely mentions the marker in a comment is never
# clobbered), and we REMOVE our own stale copy when /dev/kvm vanishes.
# NESTED-VIRT-LOSS NOTE: a worker container created WITH the device bakes it
# into its HostConfig, so if /dev/kvm later disappears (WSL nested virt lost
# across a Windows/WSL restart) that container can't restart until this block
# regenerates the override sans-device and `up -d` recreates it — which is
# exactly what a normal `./start.sh` after the restart does. Recovery is
# always: re-run ./start.sh.
OVR=docker-compose.override.yml
KVM_MARKER="# AUTO-GENERATED by start.sh: KVM device passthrough"
# Service names to attach the device to. The worker is one container per SLOT
# (worker-1, worker-2, ...), so the override must name every one of them; a
# `worker:` key alone would silently attach /dev/kvm to nothing.
#
# Read from the BASE compose file with awk rather than `docker compose config`:
# config merges the override, so if a stale override names a service that no
# longer exists, config fails — and this is the very block that fixes a stale
# override. The top-level x-worker-* anchors sit at column 0 and so cannot
# match this column-2 pattern.
_worker_svcs() {
  awk '/^  worker(-[0-9]+)?:[[:space:]]*$/ { sub(/:.*/, ""); gsub(/ /, ""); print }' \
    docker-compose.yml | sort
}
_is_gen_ovr() { [ -f "$OVR" ] && head -1 "$OVR" 2>/dev/null | grep -qxF "$KVM_MARKER"; }
EK_ENV="$(grep -E '^ENABLE_KVM=' .env 2>/dev/null | tail -1 | cut -d= -f2 | tr -d '[:space:]' || true)"
EK="${ENABLE_KVM:-${EK_ENV:-1}}"
if [ "$EK" != "0" ] && [ -e /dev/kvm ]; then
  if [ ! -f "$OVR" ] || _is_gen_ovr; then
    {
      echo "$KVM_MARKER"
      echo "# Regenerated on every ./start.sh. Set ENABLE_KVM=0 in .env (or export it in"
      echo "# your shell) to disable, or replace the marker line above to hand-manage this"
      echo "# file. Passing /dev/kvm lets the worker's qemu-system-x86_64 use -enable-kvm"
      echo "# for kernel pwn. The ':rw' drops the cgroup mknod ('m') bit qemu never needs."
      echo "services:"
      _worker_svcs | while read -r _svc; do
        [ -n "$_svc" ] || continue
        echo "  $_svc:"
        echo "    devices:"
        echo "      - /dev/kvm:/dev/kvm:rw"
      done
    } > "$OVR"
    ok "KVM present (/dev/kvm) — wrote $OVR for: $(_worker_svcs | tr '\n' ' ')"
  else
    warn "$OVR is hand-authored (no marker) — leaving it untouched; add"
    warn "  a '/dev/kvm:/dev/kvm' device to EVERY worker-N service yourself if"
    warn "  you want KVM."
  fi
elif _is_gen_ovr; then
  rm -f "$OVR"
  say "No /dev/kvm (or ENABLE_KVM=0) — removed stale generated $OVR"
fi

# --- resolve the agent CLI releases once per deployment ---------------------
# Claude/Codex/Grok are pinned into the image as EXACT versions so a build is
# reproducible, but the version itself is resolved fresh here.  That is what
# makes a deploy pick up a new stable release: the resolved string becomes a
# build arg, so Docker's cache key changes only when a channel actually moves.
# The installer additionally re-checks the command contracts the adapters rely
# on (`claude --output-format`, `codex exec --json`, `grok agent … stdio`), so a
# breaking upstream major fails the BUILD instead of a live container.
#
# Skipped under --no-build, because that run hands compose its own --no-build
# (see the up block below) and a resolved version whose only consumer is a
# build arg has nothing left to feed — all that would remain is a registry
# round-trip on the path whose entire point is "touch no images". The two
# gates are ONE fix, not two: gating this block alone would be unsafe, since a
# plain `up -d` still builds a service whose image is absent, and with the
# resolver skipped the `${CLAUDE_CLI_VERSION:-latest}` build args on the
# x-worker-service anchor and on api would bake a floating "latest" into the
# image — precisely what the fallback WARN below exists to prevent.
if [ "$NO_BUILD" -eq 0 ] && [ "${SKIP_CLI_RESOLVE:-0}" != "1" ]; then
  if CLI_RELEASES="$(scripts/resolve-agent-cli-versions.sh)"; then
    read -r CLAUDE_CLI_VERSION CODEX_CLI_VERSION GROK_CLI_VERSION <<<"$CLI_RELEASES"
    export CLAUDE_CLI_VERSION CODEX_CLI_VERSION GROK_CLI_VERSION
    say "Agent CLIs: Claude=$CLAUDE_CLI_VERSION Codex=$CODEX_CLI_VERSION Grok=$GROK_CLI_VERSION"
  else
    # A registry outage must not strand the operator: fall back to whatever the
    # existing image already has.  Never silently install a floating "latest".
    say "WARN: could not resolve stable CLI versions — reusing the current image layer"
  fi
fi

# --- HOST_DATA_DIR must name THIS checkout's data dir -----------------------
# It is a HOST path: the daemon resolves it when the worker bind-mounts a job
# into a sibling container (modules/_runner.py `_host_path`, the qemu shim,
# and the `docker run -v "$HOST_DATA_DIR/..."` recipe AUTOBOOT.md hands the
# agent). A wrong value does not fail — the daemon CREATES the missing source
# and mounts it EMPTY, so the sandbox and the challenge boot against nothing.
#
# .env.example ships it as a placeholder (/home/youruser/...) and this script
# used to only WARN that it needed editing. On this deployment it was never
# edited: /home/youruser/HexTech_CTF_TOOL/data was found on disk, root-owned,
# holding empty work/ dirs for three job ids, while every log line reported
# success. Advice that can be skipped is not a guard, so derive it.
_want_data="$PWD/data"
if [ "${HOST_DATA_DIR:-}" != "$_want_data" ]; then
  [ -n "${HOST_DATA_DIR:-}" ] \
    && warn "HOST_DATA_DIR was '${HOST_DATA_DIR}' — overriding with $_want_data"
  export HOST_DATA_DIR="$_want_data"
fi

# --- bring up / (re)build the core stack -----------------------------------
# --build is layer-cached (a no-op recreate when nothing changed) and
# self-heals a core image that was pruned, so a normal run always passes it.
#
# "Nothing changed" is not something this script can promise, though, and
# --no-build is the operator's way out of that. The resolver block above
# deliberately makes something change: its output becomes the CLI build args
# of BOTH the worker image (one image shared by every worker-N slot) and the
# api image, so on any day a channel ships a release the cache key moves, the
# 6.9 GB worker image rebuilds, and `up -d --build` recreates all twelve slots
# AND the api — killing whatever job each slot was mid-way through and
# dropping the web UI with them. That is not hypothetical: on 2026-09-02 the
# running images carried claude 2.1.158 / codex-cli 0.147.0 while the resolver
# returned 2.1.258 / 0.152.1, so the very next ./start.sh would have done it.
#
# --no-build used to reach only the four tool images above and left this line
# alone, so `./start.sh --no-build` rebuilt and recreated everything anyway —
# the opposite of the documented contract at the top of this file. Pass
# compose's OWN --no-build rather than merely dropping --build, so compose
# cannot build even on its default "build an image that is missing" policy;
# that is what lets the resolver be skipped without risking a `latest` pin.
# The cost, stated plainly because it is a real behaviour change: with a core
# image genuinely absent, --no-build now makes compose fail instead of quietly
# building one. Measured against a throwaway compose project on this host,
# `up -d --no-build` falls back to a pull and exits 1 with
#     Error response from daemon: No such image: <image>:latest
# — the same family of failure as the `pull access denied` incident at the top
# of this file, but loud and immediate rather than a job dying later. That
# matches the stance the tool-image block above already takes: under
# --no-build it warns about what is missing and builds nothing.
UP=(up -d)
if [ "$NO_BUILD" -eq 1 ]; then UP+=(--no-build); else UP+=(--build); fi
say "Bringing up core stack (redis, api, $(_worker_svcs | tr '\n' ' '))"
"${DC[@]}" "${UP[@]}"

# --- verify -----------------------------------------------------------------
say "Verifying"
fail=0

for img in "${TOOL_IMAGES[@]}"; do
  if docker image inspect "$img" >/dev/null 2>&1; then
    ok "image $img"
  else
    warn "image $img STILL MISSING"; fail=1
  fi
done

for svc in redis api $(_worker_svcs); do
  state="$("${DC[@]}" ps --format '{{.Service}} {{.State}}' 2>/dev/null | awk -v s="$svc" '$1==s{print $2}')"
  if [ "$state" = "running" ]; then
    ok "service $svc running"
  else
    warn "service $svc not running (state='${state:-absent}')"; fail=1
  fi
done

# stamp web-ui/version.json so the UI version badge shows the deployed commit
# (start.sh has cd'd to its own dir above, so the relative path is correct)
[ -x ./stamp-version.sh ] && ./stamp-version.sh || true

# --- summary ----------------------------------------------------------------
WEB_PORT="$(grep -E '^WEB_PORT=' .env 2>/dev/null | tail -1 | cut -d= -f2 | tr -d '[:space:]')"
WEB_PORT="${WEB_PORT:-8000}"
echo
if [ "$fail" -eq 0 ]; then
  printf '%sHexTech_CTF_TOOL is up.%s  Open %shttp://localhost:%s%s\n' "$B$G" "$N" "$C" "$WEB_PORT" "$N"
else
  die "startup finished with problems (see warnings above)"
fi

# --- auto-start the cloudflared OOB tunnel (auto-sets Callback URL) ----------
# Honors AUTO_TUNNEL from .env (default 1); skips cleanly if cloudflared isn't
# installed. The api is verified up above, so the tunnel can publish its URL.
# Reached only on success (die exits otherwise). Stop later: ./tunnel.sh stop
AT="$(grep -E '^AUTO_TUNNEL=' .env 2>/dev/null | tail -1 | cut -d= -f2 | tr -d '[:space:]')"
if [ "${AT:-1}" != "0" ]; then
  say "Auto-starting cloudflared OOB tunnel (set AUTO_TUNNEL=0 in .env to skip)"
  AUTO_TUNNEL=1 PROJECT_DIR="$(pwd)" WEB_PORT="$WEB_PORT" API_BASE="http://localhost:$WEB_PORT" \
    bash scripts/tunnel-autostart.sh || true
fi
